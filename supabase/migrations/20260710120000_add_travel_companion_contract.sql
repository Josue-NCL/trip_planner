    raise exception 'You do not have permission to delete this idea.' using errcode = '42501';
  end if;

  delete from public.ideas
  where id = target_idea_id and updated_at = expected_updated_at;

  if not found then
    raise exception 'This idea changed elsewhere. Reload and try again.' using errcode = '40001';
  end if;
end;
$$;

create or replace function public.promote_idea_to_schedule(
  target_idea_id bigint,
  target_trip_day_id bigint,
  target_start_time time,
  expected_idea_updated_at timestamptz
)
returns bigint
language plpgsql
security definer
set search_path = public, private
as $$
declare
  source_idea public.ideas%rowtype;
  target_trip_id bigint;
  created_schedule_item_id bigint;
begin
  select * into source_idea from public.ideas where id = target_idea_id and updated_at = expected_idea_updated_at;
  if not found then
    raise exception 'This idea changed elsewhere. Reload and try again.' using errcode = '40001';
  end if;

  select trip_id into target_trip_id from public.trip_days where id = target_trip_day_id;
  if target_trip_id is null or target_trip_id <> source_idea.trip_id or not private.can_edit_trip(target_trip_id) then
    raise exception 'You do not have permission to schedule this idea.' using errcode = '42501';
  end if;

  insert into public.schedule_items (
    trip_day_id, client_id, title, category, city, start_time, duration_minutes,
    status, notes, cost, link, map_link, sort_order, place_id, place_name,
    formatted_address, latitude, longitude, google_maps_uri, place_resolved_at
  ) values (
    target_trip_day_id, source_idea.client_id || '-scheduled-' || extract(epoch from clock_timestamp())::bigint,
    source_idea.title, source_idea.category, source_idea.city, target_start_time,
    source_idea.duration_minutes, source_idea.status, source_idea.notes, source_idea.cost,
    source_idea.link, source_idea.map_link, 0, source_idea.place_id, source_idea.place_name,
    source_idea.formatted_address, source_idea.latitude, source_idea.longitude,
    source_idea.google_maps_uri, source_idea.place_resolved_at
  ) returning id into created_schedule_item_id;

  delete from public.ideas where id = target_idea_id;
  return created_schedule_item_id;
end;
$$;

revoke all on function public.delete_schedule_item(bigint, timestamptz) from public, anon;
revoke all on function public.delete_idea(bigint, timestamptz) from public, anon;
revoke all on function public.promote_idea_to_schedule(bigint, bigint, time, timestamptz) from public, anon;
grant execute on function public.delete_schedule_item(bigint, timestamptz) to authenticated;
grant execute on function public.delete_idea(bigint, timestamptz) to authenticated;
grant execute on function public.promote_idea_to_schedule(bigint, bigint, time, timestamptz) to authenticated;

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'schedule_item_resources'
  ) then
    alter publication supabase_realtime add table public.schedule_item_resources;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'trip_notes'
  ) then
    alter publication supabase_realtime add table public.trip_notes;
  end if;
end;
$$;

commit;
